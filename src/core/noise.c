static f32 fade(f32 t) {
    return t * t * t * (t * (t * 6.0f - 15.0f) + 10.0f);
}

static f32 lerp_f(f32 t, f32 a, f32 b) {
    return a + t * (b - a);
}

static f32 grad2d(i32 hash, f32 x, f32 y) {
    /* Use low 2 bits to select one of 4 gradient directions */
    i32 h = hash & 3;
    f32 u = (h & 2) ? -x : x;
    f32 v = (h & 1) ? -y : y;
    return u + v;
}

f32 noise_perlin2d(f32 x, f32 y) {
    /* Grid cell coordinates */
    i32 xi = (i32)floorf(x) & 255;
    i32 yi = (i32)floorf(y) & 255;

    /* Fractional position within cell */
    f32 xf = x - floorf(x);
    f32 yf = y - floorf(y);

    /* Fade curves */
    f32 u = fade(xf);
    f32 v = fade(yf);

    /* Hash corner coordinates */
    i32 aa = perm[perm[xi    ] + yi    ];
    i32 ab = perm[perm[xi    ] + yi + 1];
    i32 ba = perm[perm[xi + 1] + yi    ];
    i32 bb = perm[perm[xi + 1] + yi + 1];

    /* Bilinear interpolation of gradients */
    f32 x1 = lerp_f(u, grad2d(aa, xf, yf), grad2d(ba, xf - 1.0f, yf));
    f32 x2 = lerp_f(u, grad2d(ab, xf, yf - 1.0f), grad2d(bb, xf - 1.0f, yf - 1.0f));

    return lerp_f(v, x1, x2);
}

f32 noise_fbm2d(f32 x, f32 y, i32 octaves, f32 lacunarity, f32 gain) {
    f32 sum       = 0.0f;
    f32 amplitude = 1.0f;
    f32 frequency = 1.0f;
    f32 max_amp   = 0.0f;  /* for normalization */

    for (i32 i = 0; i < octaves; i++) {
        sum       += amplitude * noise_perlin2d(x * frequency, y * frequency);
        max_amp   += amplitude;
        amplitude *= gain;
        frequency *= lacunarity;
    }

    return sum / max_amp;  /* normalize to [-1, 1] */
}
